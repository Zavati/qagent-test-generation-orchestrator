const NEVER_RETRY_CODES = new Set([
  'ENDPOINT_NOT_ELIGIBLE','ENDPOINT_GENERATION_NOT_ELIGIBLE','INSUFFICIENT_CONTEXT','ENDPOINT_GENERATION_CONTEXT_INSUFFICIENT',
  'SECURITY_BLOCK','INVALID_PROJECT_SCOPE','CONTRACT_PERMANENTLY_INVALID','UNSUPPORTED_ENDPOINT','PROJECT_NOT_FOUND','TEST_DESIGN_CONTRACT_INVALID',
  'TEST_DESIGN_SECRET_SAFE_BLOCKED','TEST_DESIGN_SEMANTIC_GROUNDING_FAILED','AI_CONFIG_REQUIRED','AI_CONFIG_INVALID',
]);
const RETRY_CODES = new Set([
  'AI_PROVIDER_TIMEOUT','AI_PROVIDER_RATE_LIMIT','AI_PROVIDER_5XX','NETWORK_TEMPORARY_FAILURE','DEPENDENCY_TEMPORARY_FAILURE','QUEUE_REDELIVERY',
  'TEST_DESIGN_PERSISTENCE_FAILED','TEST_REGISTRY_UPSTREAM_FAILED','TEST_REGISTRY_UPSTREAM_TIMEOUT','TEST_REGISTRY_UPSTREAM_UNAVAILABLE',
  'AI_REQUEST_TIMEOUT','AI_RATE_LIMITED','AI_PROVIDER_UNAVAILABLE','AI_OUTPUT_TEMPORARY_INVALID',
]);
export function classifyRetry(error) {
  const code = String(error?.code || 'ENDPOINT_GENERATION_DEPENDENCY_FAILURE');
  if (NEVER_RETRY_CODES.has(code)) return { retryable: false, code };
  if (RETRY_CODES.has(code)) return { retryable: true, code };
  if (error?.retryable === true) return { retryable: true, code };
  if (Number(error?.status) === 429 || Number(error?.status) >= 500) return { retryable: true, code };
  return { retryable: false, code };
}
